const normalize = (value) => String(value ?? "")
  .normalize("NFD")
  .replace(/[\u0300-\u036f]/g, "")
  .toLocaleLowerCase("pt-BR")
  .replace(/[^a-z0-9]+/g, " ")
  .trim();

export function localizarTarifaServico(nome) {
  const procurado = normalize(nome);
  if (!procurado) return null;
  for (const categoria of catalogoServicos) {
    const servico = categoria.servicos.find((item) => normalize(item.nome) === procurado);
    if (servico) return { ...servico, categoria: categoria.categoria };
  }
  return null;
}

export function formatarTarifaServico(servico) {
  if (servico?.valor == null) return "Convencional";
  return servico.valor.toLocaleString("pt-BR", { style: "currency", currency: "BRL" });
}
